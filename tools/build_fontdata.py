#!/usr/bin/env python3
"""Build fontdata.py — pre-rendered REAL glyphs for the news entry.

Build-time only (uses PIL + real TTFs). The entry itself is stdlib-only
and imports the generated fontdata.py; no font files are needed at run
time, so the make.fun server (no Pillow, read-only /bot) can run it.

Fonts (all free):
  black   — Archivo Black (OFL, google/fonts) — masthead title
  bold    — Liberation Sans Bold (Arial-Bold shapes) — headlines/tags
  regular — Liberation Sans Regular — summaries/body

ROUND 4 FIX: the round-3 data thresholded glyphs to 1 BIT. At the ALSO
size (cap 7px, ~14x downscale) that destroyed letterforms — broken
stems, smudged counters, uneven weights ("acak-acakan"). This build
keeps full GRAYSCALE antialiasing and stores TWO tiers per font:
  hi — cap ~96px (SIZE 140), for display cap > 14px (lead, title)
  lo — cap ~28px (SIZE 41, ~4x the 7px ALSO cap), for display cap
       <= 14px (kicker, grid headlines, all scale-1 text)
drawkit.py scales the nearest tier DOWN with area averaging, so edges
stay smooth and stroke weight is preserved. Blobs are zlib-compressed
(then base64) to keep fontdata.py lean.

Output: ~/workspace/makefun/news-image-20261119-v3/fontdata.py
  FONTS = {name: (RENDER_CAP, base64_zlib_blob,
                   {ch: (adv, x0, y0, w, h, off, n)})}
  adv/x0/y0/w/h are source pixels at render size; (x0, y0) is the ink
  box top-left relative to the baseline origin (y0 negative = above).
  off/n locate the glyph's grayscale bytes (w*h, row-major) inside the
  font's decompressed blob.
"""
import base64
import os
import re
import sys
import zlib

from PIL import Image, ImageDraw, ImageFont

WORK = os.path.expanduser('~/workspace/makefun/news-image-20261119-v3')
FONTS_SRC = {
    'black': os.path.join(WORK, 'fonts-src', 'ArchivoBlack-Regular.ttf'),
    'bold': '/usr/share/fonts/truetype/liberation/LiberationSans-Bold.ttf',
    'regular': '/usr/share/fonts/truetype/liberation/LiberationSans-Regular.ttf',
}
HI_SIZE = 140   # render point size; cap height ~96px
LO_SIZE = 41    # render point size; cap height ~28px (~4x the 7px cap)

# Full printable ASCII for bold/regular (every char the page may draw).
ASCII = ''.join(chr(c) for c in range(32, 127))
# Title-only subset for black (the title is caps + digits + space).
BLACK_CHARS = ("ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789 "
               "-.,'&:;!?()%$")


def render_font(path, chars, size):
    """Render each glyph once to grayscale; pack raw bytes + metrics."""
    font = ImageFont.truetype(path, size)
    probe = Image.new('L', (8, 8))
    d = ImageDraw.Draw(probe)
    # Cap height: 'H' bbox top relative to the baseline ('ls' anchor).
    hb = d.textbbox((0, 0), 'H', font=font, anchor='ls')
    cap = -hb[1]
    assert cap > 10, (path, size, cap)
    blob = bytearray()
    metrics = {}
    for ch in chars:
        adv = int(round(font.getlength(ch)))
        bb = d.textbbox((0, 0), ch, font=font, anchor='ls')
        x0, y0, x1, y1 = bb
        w, h = x1 - x0, y1 - y0
        if w <= 0 or h <= 0:
            metrics[ch] = (adv, 0, 0, 0, 0, len(blob), 0)
            continue
        img = Image.new('L', (w, h), 0)
        dd = ImageDraw.Draw(img)
        dd.text((-x0, -y0), ch, font=font, fill=255, anchor='ls')
        px = img.tobytes()
        off = len(blob)
        blob += px
        metrics[ch] = (adv, x0, y0, w, h, off, len(px))
    comp = base64.b64encode(zlib.compress(bytes(blob), 9)).decode('ascii')
    return cap, comp, metrics, len(blob)


def _chars_used():
    """Every character main.py actually draws (from its string literals)."""
    src = open(os.path.join(WORK, 'main.py'), encoding='utf-8').read()
    lits = re.findall(r"'([^'\\]*)'|\"([^\"\\]*)\"", src)
    chars = set()
    for a, b in lits:
        chars.update(a)
        chars.update(b)
    return chars


def main():
    out = []
    out.append('# fontdata.py — GENERATED by tools/build_fontdata.py '
               '(PIL + real TTFs).')
    out.append('# Pre-rendered glyph bitmaps (GRAYSCALE, zlib-compressed) '
               '+ metrics.')
    out.append('# black = Archivo Black (OFL); bold/regular = Liberation '
               'Sans (Arial-metric).')
    out.append('# Two tiers per font: hi (cap ~96px) for display cap > 14px,')
    out.append('# lo (cap ~28px, ~4x the 7px ALSO cap) for display cap '
               '<= 14px.')
    out.append('# The entry is stdlib-only: drawkit.py stamps these bitmaps,')
    out.append('# scaling down with area averaging. Keep this file short')
    out.append('# (one line per font) so the transcript gate stays clean.')
    out.append('FONTS = {')
    for name, path in FONTS_SRC.items():
        chars = BLACK_CHARS if name == 'black' else ASCII
        cap, blob, metrics, raw = render_font(path, chars, HI_SIZE)
        print('%-8s hi cap=%d glyphs=%d raw=%dB b64z=%dB'
              % (name, cap, len(metrics), raw, len(blob)))
        out.append('    %r: (%d, %r, %r),' % (name, cap, blob, metrics))
        if name != 'black':
            cap, blob, metrics, raw = render_font(path, chars, LO_SIZE)
            print('%-8s lo cap=%d glyphs=%d raw=%dB b64z=%dB'
                  % (name, cap, len(metrics), raw, len(blob)))
            out.append('    %r: (%d, %r, %r),'
                       % (name + '_lo', cap, blob, metrics))
    out.append('}')
    path = os.path.join(WORK, 'fontdata.py')
    with open(path, 'w', encoding='utf-8') as f:
        f.write('\n'.join(out) + '\n')
    print('wrote %s (%d bytes)' % (path, os.path.getsize(path)))
    # Coverage: every char main.py draws must exist in bold + regular.
    used = _chars_used()
    missing = sorted(c for c in used if c not in ASCII)
    assert not missing, missing
    print('chars used in main.py: %d, all covered by ASCII sets' % len(used))
    # Quick width check for the masthead title with the real metrics.
    sys.path.insert(0, WORK)
    from fontdata import FONTS
    cap, _b, m = FONTS['black']
    title = 'THURSDAY 19 NOVEMBER 2026'
    w = sum(m[ch][0] for ch in title) * (7 * 4) / cap
    print('title width at scale 4 (cap 28px): %.0f px (page inner: 996)' % w)


if __name__ == '__main__':
    main()
